#!/usr/bin/env -S node

import { existsSync, readFileSync, writeFileSync } from "node:fs"
import { gateFullCheckDays, gateLockPollSeconds } from "#limits.ts"

/**
 * limits.env, the limits a program in another language reads, generated from the Limits that state them: a shell
 * script reads it with `.`, each line `NAME=value`. `node src/data.ts` (pnpm limits:data) writes it; `--check`
 * (limits:check, in `pnpm check`) refuses it when it differs from what this would write, so it never drifts from them.
 */

/** Each limit a program in another language reads, by the name it reads it under. */
const DATA = {
	GATE_LOCK_POLL_SECONDS: gateLockPollSeconds,
	GATE_FULL_CHECK_DAYS: gateFullCheckDays
} as const

const FILE = `${import.meta.dirname}/../limits.env`

const text = [
	"# Generated by packages/limits/src/data.ts from @bjornpagen/limits (src/limits.ts), each line a Limit's value: do not",
	"# edit. pnpm limits:data writes it, and pnpm check's limits:check refuses it when it differs.",
	...Object.entries(DATA).map(([name, limit]) => `${name}=${String(limit.value)}`),
	""
].join("\n")

if (process.argv.includes("--check")) {
	if (!existsSync(FILE) || readFileSync(FILE, "utf8") !== text) {
		process.stderr.write(
			"packages/limits/limits.env differs from the limits it is generated from: run pnpm limits:data and commit it.\n"
		)
		process.exitCode = 1
	}
} else {
	writeFileSync(FILE, text)
}
